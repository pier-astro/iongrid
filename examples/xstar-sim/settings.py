"""Edit this file in each copied run directory; it records the XSTAR setup."""

from pathlib import Path

GRID_DIR = Path(__file__).resolve().parent

# Options are "cartesian" or "lhs".
GRID_MODE = "cartesian"


# =============================================================================
# Cartesian grid
# =============================================================================
# Used only when GRID_MODE = "cartesian".
LOGXI_VALUES = [3.0, 4.0]
VTURB_VALUES = [100.0, 1000.0]
LOG_NH_VALUES = [22.0, 23.0]
FEABUND_VALUES = [0.5, 1.5]
GAMMA_VALUES = [1.5, 2.5]


# =============================================================================
# Latin-hypercube sampling (LHS)
# =============================================================================
# Directory in which make-lhs.py writes the generated grid, summaries and plots.
LHS_OUTPUT_DIR = GRID_DIR / "new_parameter_grid"
# Bounds for the continuously sampled parameters.
LHS_BOUNDS = {
    "logxi": (3.0, 4.0),
    "vturb": (100.0, 1000.0),
    "log_nh": (22.0, 23.0),
    "feabund": (0.5, 1.5),
    "gamma": (1.5, 2.5),
}

# Each population generates an independent LHS sample with its own seed.
# Every population must contain at least 2 * len(LHS_BOUNDS) samples to accommodate the boundary anchors generated by iongrid.xstar.lhs.
LHS_POPULATIONS = [
    {
        "name": "baseline",
        "n_samples": 500,
        "seed": 12345,
    },
]
# Turbulent velocity sampling:
#   "linear" -> uniform in physical velocity (km/s).
#   "log"    -> uniform in log10(vturb).
LHS_VTURB_SAMPLING = "log"

# Optional existing parameter grid used to exclude previously simulated points. Set to a CSV file if you want to avoid duplicating existing simulations.
LHS_EXISTING_GRID_FILE = None
# Map each parameter to its column name in the existing CSV, if different.
LHS_EXISTING_COLUMN_MAP = {}
# Supply fixed values for parameters missing from the existing CSV, if needed.
LHS_EXISTING_FILL_VALUES = {}
# Diagnostic plots produced by make-lhs.py.
LHS_SAVE_PLOTS = True
LHS_SHOW_PLOTS = False
LHS_HISTOGRAM_BINS = 40


# =============================================================================
# Fixed XSTAR configuration
# =============================================================================
LOG_DENSITY = 12.0
LUMINOSITY_38 = 1.0e9

# None uses the default SED configuration. Alternatively, provide a path such as GRID_DIR / "sed.dat".
SED_FILE = None
XSTAR_OPTIONS = {
    "emult": 0.5,
    "taumax": 5.0,
    "xeemin": 0.1,
    "critf": 1e-5,
}
XSTAR_PATH = "xstar"


# =============================================================================
# FITS packing and cleaning
# =============================================================================
# Options: "raw", "clean" or "both".
CLEAN = "raw"
# |1 - T| below EPS_T counts as no absorption.
EPS_T = 1e-5
# Emission residual below EPS_E * max(total, continuum) counts as no line emission.
EPS_E = 1e-5

# =============================================================================
# Build the setup consumed by sim-local.py
# =============================================================================

_COMMON = dict(
    log_density=LOG_DENSITY,
    luminosity_38=LUMINOSITY_38,
    xstar_options=XSTAR_OPTIONS,
    sed_file=SED_FILE,
)

if GRID_MODE == "cartesian":
    SETUP = dict(
        logxi_values=LOGXI_VALUES,
        vturb_values=VTURB_VALUES,
        log_nh_values=LOG_NH_VALUES,
        feabund_values=FEABUND_VALUES,
        gamma_values=GAMMA_VALUES,
        **_COMMON,
    )

elif GRID_MODE == "lhs":
    LHS_FILE = LHS_OUTPUT_DIR / "new_parameter_grid.csv"
    SETUP = dict(
        lhs_file=LHS_FILE,
        **_COMMON,
    )

else:
    raise ValueError("GRID_MODE must be 'cartesian' or 'lhs'")

